import esbuild from 'esbuild';
import process from 'process';
import { readFileSync } from 'node:fs';
import { builtinModules } from 'node:module';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
/*
${readFileSync(new URL('./THIRD_PARTY_NOTICES.md', import.meta.url), 'utf8')}
*/
`;

const prod = process.argv[2] === 'production';
const once = prod || process.argv.includes('--once');

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
 define: { __SPORTS_DEV__: JSON.stringify(!prod) },
 bundle: true,
 metafile: true,
 plugins: [{ name: 'drop-unused-sdk-filesystem-imports', setup(build) {
  // garminconnect-js also exports a FileTokenStore. We use only our Obsidian
  // secret-storage implementation. An unused Node import has no initialization
  // work to retain; referenced filesystem functions would still be emitted.
  build.onResolve({ filter: /^(?:node:)?fs(?:\/promises)?$/ }, args => ({ path: args.path, external: true, sideEffects: false }));
 } }],
	loader: { '.xlsx': 'binary', '.ods': 'binary', '.svg': 'text', '.md': 'text' },
	external: [
		'node:*',
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (once) {
 const result = await context.rebuild();
 if (prod) {
  if (Object.keys(result.metafile.inputs).some(path => /(?:^|\/)src\/dev\//.test(path))) throw new Error('Development modules must not be included in release builds.');
  if (readFileSync('main.js', 'utf8').includes('dev-local-workbook')) throw new Error('Development workbook override leaked into release build.');
 const filesystemImports = Object.values(result.metafile.outputs).flatMap(output => output.imports)
  .filter(item => /^(?:node:)?fs(?:\/|$)/.test(item.path));
 if (filesystemImports.length) throw new Error('Runtime filesystem access is forbidden in the cloud-only plugin.');
 }
	await context.dispose();
	process.exit(0);
} else {
	await context.watch();
}
